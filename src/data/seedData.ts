/**
 * Creates a Date instance relative to the start of today (local time).
 */
export function getRelativeDate(dayOffset: number, hour: number, minute: number = 0): Date {
  const d = new Date();
  d.setDate(d.getDate() + dayOffset);
  d.setHours(hour, minute, 0, 0);
  return d;
}

